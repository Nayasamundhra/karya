"""Karya FastAPI application: composition root.

This module wires things together and contains no business logic. It is the one
place that decides middleware order, mounts routers, registers exception handlers
and owns the process lifecycle.

The application is built by :func:`create_app`, which takes its configuration as
an argument. ``app = create_app()`` at the bottom is what ``uvicorn app.main:app``
loads; the parameter exists so the wiring itself is testable - CORS behaviour,
security headers and whether the docs are served are *configuration-dependent*
behaviour, and a test that cannot vary the configuration cannot check any of them.

**Middleware order** (outermost first) is not arbitrary:

1. :class:`~app.middleware.security_headers.SecurityHeadersMiddleware` -
   outermost, so *every* response carries the hardening headers, including the
   responses generated by the middleware below it.
2. :class:`~app.middleware.request_context.RequestContextMiddleware` - correlation
   id, access log, and the last-resort 500. Outside CORS so a rejected preflight is
   still logged and still traceable.
3. ``CORSMiddleware`` - inside the two above so the responses it generates get
   both, and outside the size limits so a 413 still carries CORS headers and a
   browser reports the real status rather than an opaque CORS failure.
4. :class:`~app.middleware.request_limits.RequestLimitsMiddleware` - innermost,
   but still ahead of routing, so an oversized body is refused before it is
   buffered or parsed.
"""

