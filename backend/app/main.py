from app.middleware.request_context import REQUEST_ID_HEADER, RequestContextMiddleware
from app.middleware.request_limits import RequestLimitsMiddleware
from app.middleware.security_headers import SecurityHeadersMiddleware

logger = logging.getLogger(__name__)

DESCRIPTION = """
Multi-tenant staff attendance with **server-verified presence**.

Every request is scoped to the authenticated user's own tenant. Identity, role,
tenant, GPS validity, geofence distance, QR validity and the attendance timestamp
are all determined by the server; no client-supplied value influences any of them.

**Authentication.** `POST /api/v1/auth/login` returns a short-lived JWT access
token and a long-lived, revocable refresh token. Send the access token as
`Authorization: Bearer <token>`. Refresh tokens must be rotated - the presented
token is revoked as part of a successful rotation, so replaying one fails.

**Errors.** Every error response is `{"detail": ...}`. Validation failures return
422 with a list of `{type, loc, msg}` under `detail`; the submitted value is never
echoed back. Rate-limited requests return 429 with a `Retry-After` header. Every
response, success or failure, carries an `X-Request-ID` header - quote it when
reporting a problem.

**Presence and attendance refusals are not HTTP errors.** A well-formed request
refused on its merits - outside the geofence, QR already used, already checked in -
returns **200** with `verified: false` or `success: false` and a machine-readable
`reason`. 4xx is reserved for requests that could not be processed at all.

**Nothing is ever deleted.** There is no `DELETE` method anywhere in this API.
Users move between `ACTIVE` and `INACTIVE`; attendance events are immutable.
"""

