def build_lifespan(config: Settings):  # noqa: ANN201 - returns an async CM factory
    """Create the lifespan handler for an application built from ``config``."""

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        """Process lifecycle.

        Startup deliberately does **not** touch the database. A dependency being
        briefly unavailable should not prevent the process from starting and
        reporting itself unready - that is what ``/ready`` is for, and a container
        that refuses to start cannot report anything at all.

        Shutdown disposes the connection pool. Uvicorn stops accepting connections
        and waits for in-flight requests before running this, so closing the pool
        here cannot interrupt a request that is still being served. Nothing else
        needs stopping: Karya runs no background tasks, timers or workers, which is
        why graceful shutdown is four lines rather than a subsystem.
        """
        configure_logging(config)
        logger.info(
            "application_startup",
            extra={
                "event": "application_startup",
                "version": APP_VERSION,
                "environment": config.environment.value,
                # The password-free rendering. The raw URL is never logged.
                "database": config.safe_database_uri,
                "auth_configured": config.is_auth_configured,
                "rate_limit_enabled": config.rate_limit_enabled,
                "cors_origin_count": len(config.cors_origins),
                "docs_enabled": config.docs_enabled,
            },
        )
        try:
            yield
        finally:
            logger.info(
                "application_shutdown", extra={"event": "application_shutdown"}
            )
            dispose_engine()

    return lifespan


def create_app(config: Settings | None = None) -> FastAPI:
    """Build a fully wired Karya application."""
    config = config or settings

    app = FastAPI(
        title=config.app_name,
        version=APP_VERSION,
        summary="Multi-tenant staff attendance and presence verification platform.",
        description=DESCRIPTION,
        openapi_tags=TAGS_METADATA,
        lifespan=build_lifespan(config),
        # Turning the docs off removes the schema endpoint too, which is the point:
        # they are one decision, not two.
        docs_url="/docs" if config.docs_enabled else None,
        redoc_url="/redoc" if config.docs_enabled else None,
        openapi_url="/openapi.json" if config.docs_enabled else None,
    )

    register_exception_handlers(app)

    # --- Middleware (added innermost first; see the module docstring) --------
    app.add_middleware(RequestLimitsMiddleware, config=config)

    # CORS is opt-in per origin, read from CORS_ALLOWED_ORIGINS. There is no
    # wildcard fallback: with credentialed requests a wildcard is both invalid per
    # the CORS spec and unsafe, and `Settings` rejects one outright. An empty list
    # means no browser origin is permitted, which is the safe default for a
    # backend-only deployment - and in that case the middleware is not installed at
    # all, so no `Access-Control-Allow-*` header is ever emitted.
    if config.cors_origins:
        app.add_middleware(
            CORSMiddleware,
            allow_origins=config.cors_origins,
            allow_credentials=True,
            allow_methods=["GET", "POST", "PATCH", "PUT", "DELETE", "OPTIONS"],
            allow_headers=["Authorization", "Content-Type", REQUEST_ID_HEADER],
            # Without this a browser cannot read the correlation id, which makes it
            # useless to the frontend that would otherwise report it.
            expose_headers=[REQUEST_ID_HEADER, "Retry-After"],
        )

    app.add_middleware(RequestContextMiddleware)
    app.add_middleware(SecurityHeadersMiddleware, config=config)

    app.include_router(probes.router)
    app.include_router(api_router, prefix=API_V1_PREFIX)
    return app


#: The ASGI application `uvicorn app.main:app` loads.
app = create_app()
